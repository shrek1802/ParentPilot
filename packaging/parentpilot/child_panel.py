#!/usr/bin/python3
"""ParentPilot child-only XFCE panel layout.

The parent installer calls write_child_panel for a freshly created account.
During an upgrade, --repair runs as the *child Linux user*, never root,
and changes ONLY a recognised ParentPilot-generated XFCE panel. No other
parent/child files or XFCE account settings are reset.
"""
from pathlib import Path
import os
import pwd
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET

# The icon theme on fresh Mint installations varies. Use bundled SVG files
# rather than bare theme names ('chromium', 'system-file-manager') that can
# resolve to generic or blank placeholders on other laptops.
ICON_DIR = Path('/usr/lib/parentpilot/icons')
ICONS = {
    10: ICON_DIR / 'browser.svg',
    11: ICON_DIR / 'files.svg',
    12: ICON_DIR / 'youtube.svg',
    13: ICON_DIR / 'netflix.svg',
}


def ensure_launcher_icon(source, icon_file):
    """Update only the Icon key of ParentPilot's own child launchers.

    Preserve the current Exec, YouTube choice, arguments and user preferences.
    If an existing launcher is missing, refuse to invent a replacement.
    """
    source = Path(source)
    if not source.is_file() or source.is_symlink():
        return False
    lines = source.read_text(encoding='utf8').splitlines()
    if not lines or '[Desktop Entry]' not in lines:
        return False
    seen = False
    in_entry = False
    updated = []
    for line in lines:
        if line.startswith('[') and line.endswith(']'):
            in_entry = (line == '[Desktop Entry]')
        if in_entry and line.startswith('Icon='):
            if not seen:
                updated.append('Icon=' + str(icon_file))
                seen = True
            continue
        updated.append(line)
    if not seen:
        index = updated.index('[Desktop Entry]') + 1
        updated.insert(index, 'Icon=' + str(icon_file))
    fixed = '\n'.join(updated) + '\n'
    if source.read_text(encoding='utf8') != fixed:
        source.write_text(fixed, encoding='utf8')
    return True


def prop(parent, name, typ=None, value=None):
    attrs={'name':name}
    if typ is not None:
        attrs['type'] = typ
        # XFCE's xfconf serialisation omits value for array and empty nodes.
        if typ not in ('array', 'empty') and value is not None:
            attrs['value'] = str(value)
    return ET.SubElement(parent,'property',attrs)


def array(parent,name,typ,values):
    p=prop(parent,name,'array','')
    for v in values: ET.SubElement(p,'value',{'type':typ,'value':str(v)})
    return p


# ONLY alternative browser launchers are hidden from the child's applications
# menu. ParentPilot is a normal Linux Mint desktop for learning; VLC, LibreOffice,
# terminal, file manager, settings, software manager, and every other program
# remain accessible as installed. This is cosmetic and not a security boundary.
OTHER_BROWSER_DESKTOPS = (
    'firefox.desktop', 'firefox-esr.desktop', 'org.mozilla.firefox.desktop',
    'google-chrome.desktop', 'google-chrome-stable.desktop',
    'com.google.Chrome.desktop',
    'brave-browser.desktop', 'brave-browser-beta.desktop',
    'com.brave.Browser.desktop',
    'microsoft-edge.desktop', 'microsoft-edge-stable.desktop',
    'opera.desktop', 'vivaldi-stable.desktop',
    'epiphany.desktop', 'org.gnome.Epiphany.desktop',
    'org.kde.falkon.desktop', 'falkon.desktop',
    'librewolf.desktop', 'torbrowser.desktop',
)

# The old Preview 8-13 setup accidentally hid educational/desktop programs.
# We reverse only entries that EXACTLY match our old autogenerated text;
# don't delete or change any real application files or the child's own edits.
LEGACY_NON_BROWSER_HIDDEN = (
    'xfce4-terminal.desktop', 'org.xfce.Terminal.desktop',
    'org.xfce.terminal.desktop', 'gnome-terminal.desktop',
    'mintinstall.desktop', 'synaptic.desktop',
    'software-properties-gtk.desktop', 'org.gnome.Software.desktop',
    'timeshift-gtk.desktop', 'gdebi.desktop',
    'org.xfce.appfinder.desktop',
)
OLD_HIDDEN_ENTRY = (
    '[Desktop Entry]\nType=Application\n'
    'Name=Hidden from child menu\nHidden=true\n'
)


def restore_normal_apps_and_hide_other_browsers(home):
    """Child-only menu repair, preserving custom files and all installed apps."""
    applications = Path(home) / '.local/share/applications'
    applications.mkdir(parents=True, exist_ok=True)

    for name in LEGACY_NON_BROWSER_HIDDEN:
        entry = applications / name
        if entry.is_file() and not entry.is_symlink():
            if entry.read_text(encoding='utf8') == OLD_HIDDEN_ENTRY:
                entry.unlink()

    # Remove only the two temporary menu entries generated by Preview 13,
    # avoiding duplicate Files / Log out entries in XFCE's restored full menu.
    legacy_generated = {
        'parentpilot-files.desktop': (
            '[Desktop Entry]\nType=Application\nName=Files\n'
            'Exec=thunar\nIcon=' + str(ICONS[11]) +
            '\nTerminal=false\nCategories=Utility;\n'
        ),
        'parentpilot-logout.desktop': (
            '[Desktop Entry]\nType=Application\nName=Log out\n'
            'Exec=xfce4-session-logout\nIcon=system-log-out\n'
            'Terminal=false\nCategories=System;\n'
        ),
    }
    for name, original in legacy_generated.items():
        entry = applications / name
        if entry.is_file() and not entry.is_symlink():
            if entry.read_text(encoding='utf8') == original:
                entry.unlink()

    for name in OTHER_BROWSER_DESKTOPS:
        entry = applications / name
        if entry.is_symlink():
            continue
        if entry.exists():
            # Never clobber a child's own desktop-file edits.
            continue
        entry.write_text(
            '[Desktop Entry]\nType=Application\n'
            'Name=Hidden alternative web browser\nHidden=true\n',
            encoding='utf8',
        )

    # ParentPilot Preview 13's restrictive menu is no longer used. Remove
    # only a file with the distinct allowlisted structure generated by us.
    old_menu = Path(home) / '.config/menus/parentpilot.menu'
    if old_menu.is_file() and not old_menu.is_symlink():
        try:
            parsed = ET.parse(old_menu).getroot()
            included = parsed.findall('./Include/Filename')
            if (parsed.findtext('Name') == 'ParentPilot'
                    and len(included) in (4, 5)
                    and all((e.text or '').startswith('parentpilot-')
                            for e in included)):
                old_menu.unlink()
        except (ET.ParseError, OSError):
            pass


def make_vlc_child_shortcut(home):
    """Pin VLC without replacing a custom user-defined desktop entry."""
    entry = Path(home) / '.local/share/applications/parentpilot-vlc.desktop'
    text = (
        '[Desktop Entry]\nType=Application\n'
        'Name=VLC Media Player\n'
        'Comment=Play videos, music and DVDs\n'
        'Exec=vlc %U\nIcon=vlc\n'
        'Terminal=false\nCategories=AudioVideo;Player;\n'
        'MimeType=video/mp4;video/x-matroska;audio/mpeg;\n'
    )
    if entry.is_symlink():
        raise RuntimeError('Unsafe VLC desktop entry link')
    if not entry.exists():
        entry.write_text(text, encoding='utf8')
    return entry



# Use the actual Mint XFCE Whisker configuration where available, instead of
# drawing a faux Mint menu or imposing ParentPilot's old restricted app list.
MINT_WHISKER_TEMPLATES = (
    Path('/usr/share/mint-configuration-xfce/xfce4/panel/whiskermenu-1.rc'),
    Path('/usr/share/mint-artwork/xfce/xfce4/panel/whiskermenu-1.rc'),
)


def ensure_mint_whisker_settings(home, templates=None):
    """Restore Mint's native Whisker appearance without overwriting preferences.

    Whisker saves its settings in whiskermenu-1.rc, NOT xfconf's plugin
    button-icon/show-button-* properties. Preserve existing child Whisker
    favourites/preferences if they already have a valid config.
    """
    dest = Path(home) / '.config/xfce4/panel/whiskermenu-1.rc'
    if dest.is_symlink():
        raise RuntimeError('Unsafe Whisker configuration symlink.')
    if dest.is_file():
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    for source in (MINT_WHISKER_TEMPLATES if templates is None else templates):
        source = Path(source)
        if source.is_file():
            try:
                data = source.read_text(encoding='utf8')
            except (UnicodeError, OSError):
                continue
            if 'button-icon=' in data or 'show-button-title=' in data:
                # Keep Mint's own menu look, but make Chromium/ParentPilot
                # the browser on the default favourites page, not Firefox.
                lines = []
                for line in data.splitlines():
                    if line.startswith('favorites='):
                        fav = [v.strip() for v in line[10:].split(',') if v.strip()]
                        browser_ids = set(OTHER_BROWSER_DESKTOPS)
                        fav = [v for v in fav if v not in browser_ids]
                        if 'parentpilot-browser.desktop' not in fav:
                            fav.insert(0, 'parentpilot-browser.desktop')
                        line = 'favorites=' + ','.join(fav)
                    lines.append(line)
                dest.write_text('\n'.join(lines) + '\n', encoding='utf8')
                return dest
    # Debian/Xubuntu or Mint with no installed artwork template. Still use
    # the real Whisker plugin and search/categories; no curated-only menu.
    dest.write_text(
        'button-icon=linuxmint-logo-ring-symbolic\n'
        'show-button-icon=true\n'
        'show-button-title=false\n'
        'button-title=Menu\n'
        'favorites=parentpilot-browser.desktop,thunar.desktop,vlc.desktop\n'
        'menu-width=520\nmenu-height=560\n',
        encoding='utf8',
    )
    return dest


def write_child_panel(home, group, youtube=True, netflix=True):
    """Only for freshly created child homes. Single bottom XFCE panel with curated launchers.
    This customisation changes visible launchers, not access control or parent panel.
    """
    conf=home/'.config/xfce4/xfconf/xfce-perchannel-xml'
    conf.mkdir(parents=True,exist_ok=True)
    root=ET.Element('channel',{'name':'xfce4-panel','version':'1.0'})
    prop(root,'configver','int',2)
    panels=array(root,'panels','int',[1])
    panel=prop(panels,'panel-1','empty','')
    prop(panel,'position','string','p=10;x=0;y=0')
    prop(panel,'position-locked','bool','true')
    # Full learning desktop: normal application menu + running-window buttons,
    # followed by centred family quick launches and a compact status tray.
    prop(panel,'size','uint',44)
    prop(panel,'icon-size','uint',32)
    prop(panel,'length','uint',100)
    prop(panel,'length-adjust','bool','false')
    prop(panel,'autohide-behavior','uint',0)
    launcher_ids=[10,11]+([12] if youtube else [])+([13] if netflix else [])+[14]
    # The dedicated XFCE Power Manager plugin provides a reliable battery
    # indicator even when the status tray does not expose a power icon.
    # Package xfce4-power-manager-plugins is an explicit DEB dependency.
    plugin_ids=[1,17,18,*launcher_ids,19,21,23,22]
    array(panel,'plugin-ids','int',plugin_ids)
    plugins=prop(root,'plugins','empty','')
    # Linux Mint XFCE's original full-featured Start menu is Whisker,
    # not XFCE's basic applicationsmenu plugin.
    app_menu = prop(plugins,'plugin-1','string','whiskermenu')
    prop(app_menu,'show-button-title','bool','false')
    # Whisker reads the normal full applications menu. Its appearance and
    # favourites are configured by whiskermenu-1.rc below, not XFCE's basic
    # applicationsmenu configuration fields.
    labels={10:'parentpilot-browser.desktop',11:'thunar.desktop',12:'parentpilot-youtube.desktop',13:'parentpilot-netflix.desktop',14:'parentpilot-vlc.desktop'}
    tasklist=prop(plugins,'plugin-17','string','tasklist')
    prop(tasklist,'grouping','uint',1)
    # Separator 18 and 19 expand equally; the tray and clock retain space
    # on the right while the child app shortcuts form an uncluttered dock.
    for spacer_id in (18,19):
        spacer = prop(plugins, f'plugin-{spacer_id}', 'string', 'separator')
        prop(spacer, 'style', 'uint', 0)
        prop(spacer, 'expand', 'bool', 'true')
    for number in launcher_ids:
        p=prop(plugins,f'plugin-{number}','string','launcher')
        array(p,'items','string',[labels[number]])
    # Status icons, a native battery indicator and clock are kept together
    # on the right. No polling applet or elevated background process.
    tray = prop(plugins,'plugin-21','string','systray')
    prop(tray, 'icon-size', 'int', 20)
    prop(tray, 'single-row', 'bool', 'true')
    prop(plugins,'plugin-23','string','power-manager-plugin')
    clock = prop(plugins,'plugin-22','string','clock')
    prop(clock, 'mode', 'uint', 2)
    prop(clock, 'digital-format', 'string', '%H:%M')
    ET.indent(root,space='  ')
    ET.ElementTree(root).write(conf/'xfce4-panel.xml',encoding='utf-8',xml_declaration=True)
    restore_normal_apps_and_hide_other_browsers(home)
    # Reapply the curated dock through the active XFCE settings service on
    # the child's NEXT login. Updating the offline XML alone can be ignored
    # by a cached xfconfd process.
    startup = home/'.config/autostart'
    startup.mkdir(parents=True, exist_ok=True)
    (startup/'parentpilot-panel-refresh.desktop').write_text(
        '[Desktop Entry]\nType=Application\n'
        'Name=ParentPilot Panel Layout\n'
        'Exec=/usr/bin/python3 /usr/lib/parentpilot/child_panel.py --apply-session\n'
        'Terminal=false\nOnlyShowIn=XFCE;\n'
        'X-GNOME-Autostart-enabled=true\nNoDisplay=true\n',
        encoding='utf8')
    # VLC is a real standalone media player, not another Chromium shortcut.
    make_vlc_child_shortcut(home)
    pdir=home/'.config/xfce4/panel'
    ensure_mint_whisker_settings(home)
    for number in launcher_ids:
        folder=pdir/f'launcher-{number}'
        folder.mkdir(parents=True,exist_ok=True)
        source=home/'.local/share/applications'/labels[number]
        if number==11:
            # The stock Thunar icon name depends on the theme: use a stable
            # folder SVG while leaving the file manager executable unchanged.
            (folder/'thunar.desktop').write_text(
                '[Desktop Entry]\nType=Application\nName=Files\nExec=thunar\n'
                'Icon=' + str(ICONS[number]) + '\nTerminal=false\n',
                encoding='utf8',
            )
        elif number==14:
            shutil.copy2(source, folder/labels[number])
        elif ensure_launcher_icon(source, ICONS[number]):
            shutil.copy2(source, folder/labels[number])
        else:
            raise RuntimeError('ParentPilot child shortcut missing: ' + labels[number])



def existing_parentpilot_panel(home):
    """Return True only for our own existing panel, not a custom XFCE desktop."""
    home = Path(home)
    config = home / '.config/xfce4/xfconf/xfce-perchannel-xml/xfce4-panel.xml'
    shortcut = home / '.config/xfce4/panel/launcher-10/parentpilot-browser.desktop'
    if config.is_symlink() or shortcut.is_symlink():
        return False
    if not config.is_file() or not shortcut.is_file():
        return False
    try:
        root = ET.parse(config).getroot()
        return (
            root.tag == 'channel' and root.get('name') == 'xfce4-panel'
            and root.find(".//property[@name='plugin-10']") is not None
            and 'parentpilot-browser.desktop' in shortcut.name
        )
    except (ET.ParseError, OSError):
        return False


def repair_child_panel():
    """Maintain only our own shortcuts; never rebuild a customised panel.

    The previous upgrade path called write_child_panel, which replaced the
    entire XFCE plugin list and removed user-pinned Kodi/game launchers.
    Preserve both the offline XML and the live xfconf plugin order verbatim.
    """
    if os.geteuid() == 0:
        raise RuntimeError('Child panel repair must not run as root.')
    account = pwd.getpwuid(os.getuid())
    home = Path(account.pw_dir)
    if not existing_parentpilot_panel(home):
        print('SKIPPED: child panel is not ParentPilot-managed.')
        return
    restore_normal_apps_and_hide_other_browsers(home)
    ensure_mint_whisker_settings(home)
    make_vlc_child_shortcut(home)
    print('Child menu checked; pinned launchers and XFCE panel preserved.')



# XFCE saves its panel in xfconf, not just xfce4-panel.xml. A resident xfconfd
# process can keep the previous left-aligned layout after a package upgrade,
# or overwrite edited XML when the child next signs in. Apply layout once in
# the CHILD's own graphical session, through xfconf-query, after XFCE starts.
LAYOUT_REVISION = 'mint-whisker-power-indicator-v8'


def xfconf_commands_for_panel(home):
    """Never reapply a fixed plugin list over custom pins.

    Modern ParentPilot does not need to change the panel on upgrades. The
    fresh setup writes its XML once and XFCE owns it thereafter. In particular
    do not call xfconf-query on /panels/panel-1/plugin-ids, or overwrite a
    launcher that a family has pinned (for example Kodi).
    """
    return []



def apply_session_panel(home=None, runner=subprocess.run):
    """Legacy child autostart is now a no-op to preserve a customised panel.

    No xfconf writes or panel restarts; existing Kodi/taskbar pins are safe.
    """
    if os.geteuid() == 0:
        raise RuntimeError('Refusing to manage a root XFCE panel.')
    account = pwd.getpwuid(os.getuid())
    if not existing_parentpilot_panel(Path(home or account.pw_dir)):
        print('SKIPPED: this is not a managed child panel.')
        return False
    print('ParentPilot leaves pinned XFCE panel apps unchanged.')
    return True


if __name__ == '__main__':
    if sys.argv[1:] == ['--repair']:
        repair_child_panel()
    elif sys.argv[1:] == ['--apply-session']:
        apply_session_panel()
    else:
        raise SystemExit('Usage: child_panel.py --repair | --apply-session')
